    for eps, kn in ((panchatantra, PANCHATANTRA_KN), (jataka, JATAKA_KN)):
        assert len(eps) == len(kn), (len(eps), len(kn))
        for ep, (title, moral, caps, alts) in zip(eps, kn):
            ep["title"], ep["moral"] = title, moral
            for p, cap, alt in zip(ep["panels"], caps, alts):
                p["cap"], p["alt"] = cap, alt
                p["items"] = [(("text", it[1], it[2], SOUND.get(it[3], it[3])) if it[0] == "text" else it) for it in p.get("items", [])]
